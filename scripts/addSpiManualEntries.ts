function appendToSheet(
  wb: XLSX.WorkBook,
  sheetName: string,
  entries: Entry[],
): { startNo: number; endNo: number } {
  const ws = wb.Sheets[sheetName];
  if (!ws) throw new Error(`シートが見つかりません: ${sheetName}`);

  // 既存の最大 No. を求める
  const rows = XLSX.utils.sheet_to_json<Record<string, unknown>>(ws, {
    defval: null,
  });
  let maxNo = 0;
  for (const r of rows) {
    const n = Number(r['No.']);
    if (Number.isFinite(n) && n > maxNo) maxNo = n;
  }

  // 列の並び:  No. | 問題文 | 採用解答 | 信頼度 | ランク | 要検証 | 総票数 | 加重票数 | 得票内訳 | 出典ファイル数
  const newRows: unknown[][] = entries.map((e, i) => [
    maxNo + i + 1,
    e.q,
    e.a,
    1.0,
    'A',
    '',
    1,
    1.0,
    `${e.a}:1`,
    1,
  ]);

  const range = XLSX.utils.decode_range(ws['!ref'] || 'A1');
  const startRow = range.e.r + 1; // 既存最終行の次から
  XLSX.utils.sheet_add_aoa(ws, newRows, { origin: { r: startRow, c: 0 } });

  return { startNo: maxNo + 1, endNo: maxNo + entries.length };
}

async function main() {
  if (!existsSync(SPI_XLSX)) {
    console.error(`❌ Excel が見つかりません: ${SPI_XLSX}`);
    process.exit(1);
  }

  console.log('▶ Excel 読み込み中…');
  const buf = await readFile(SPI_XLSX);
  const wb = XLSX.read(buf, { type: 'buffer', cellStyles: true });

  const langRange = appendToSheet(wb, '言語_採用', LANG_ENTRIES);
  console.log(
    `  + 言語_採用:   ${LANG_ENTRIES.length} 行追加 (No. ${langRange.startNo}〜${langRange.endNo})`,
  );

  const higengoRange = appendToSheet(wb, '非言語_採用', HIGENGO_ENTRIES);
  console.log(
    `  + 非言語_採用: ${HIGENGO_ENTRIES.length} 行追加 (No. ${higengoRange.startNo}〜${higengoRange.endNo})`,
  );

  console.log('▶ Excel 書き出し中…');
  const out = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }) as Buffer;
  await writeFile(SPI_XLSX, out);

  console.log(`\n✅ 完了: ${path.relative(ROOT, SPI_XLSX)}`);
  console.log('   次は: npm run generate:webtest-others');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
